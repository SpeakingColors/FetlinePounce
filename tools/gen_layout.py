#!/usr/bin/env python3
"""Generate src/editor/Layout.h from docs/mockup/layout.json (made by tools/dump_layout.py from the
mockup page). Every position, size, label and tooltip of the native editor comes from the mockup this
way. The mockup has a preview rig under the displays ("not part of the plugin"); the real window leaves
it out, so everything below the displays moves up by the rig height. Run from the repo root."""
import json
d = json.load(open('docs/mockup/layout.json'))
RIG = d['rig'][3]
for k in ('cheekL', 'cheekR', 'body', 'meters'): d[k][3] -= RIG
d['foot'][1] -= RIG; d['winsz'][1] -= RIG; d['footText'][1] -= RIG
H = int(d['cheekL'][3])
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\u00b5', '\\u00b5') + '"'
def f(v):
    t = '%g' % v
    if 'e' in t: t = '%.4f' % v
    return t + ('' if '.' in t else '.0') + 'f'
def rc(r): return '{ ' + ', '.join(f(v) for v in r) + ' }'
o = ['// GENERATED by tools/gen_layout.py from docs/mockup/layout.json. Do not edit by hand.', '#pragma once', 'namespace layout {',
     'struct Rc { float x, y, w, h; };', 'struct Cell { const char* name; const char* label; const char* tip; Rc labelR, knob, end0R, end1R, val; const char* end0; const char* end1; };',
     'struct Key { const char* text; Rc r; const char* tip; const char* name; };',
     'constexpr int W = 1200, H = %d;' % H]
for k in ['cheekL', 'cheekR', 'hdr', 'body', 'top', 'ctl', 'disp', 'meters', 'foot', 'logo', 'n1', 'n2', 's87', 'pPrev', 'pName', 'pNext', 'pSave', 'bBypass', 'bGuide', 'bSettings', 'bAbout',
          'vu', 'cvCurve', 'cvHist', 'cvTime', 'cvIn', 'cvOut', 'pkIn', 'pkOut', 'winsz', 'footText', 'kHP', 'mixKnob', 'mixVal']:
    o.append('constexpr Rc %s = %s;' % (k, rc(d[k])))
o.append('constexpr Rc mixCap = %s;' % rc(d['mixCap']['r']))
cells = []
for c in d['kcells']:
    cells.append('{ %s, %s, %s, %s, %s, %s, %s, %s, %s, %s }' % (q(c['id']), q(c['lab']), q(c['knobTip']), rc(c['labR']), rc(c['knob']), rc(c['ends'][0]['r']), rc(c['ends'][1]['r']), rc(c['val']), q(c['ends'][0]['t']), q(c['ends'][1]['t'])))
o.append('constexpr Cell cells[%d] = {\n    ' % len(cells) + ',\n    '.join(cells) + ' };')
g = d['grps']
for name, grp in (('ratio', g[0]), ('meter', g[1])):
    o.append('constexpr Rc %sCap = %s; constexpr const char* %sCapText = %s;' % (name, rc(grp['capR']), name, q(grp['cap'])))
    ks = ['{ %s, %s, %s, %s }' % (q(k['t']), rc(k['r']), q(k['tip']), q(k['aria'])) for k in grp['keys']]
    o.append('constexpr Key %sKeys[%d] = {\n    ' % (name, len(ks)) + ',\n    '.join(ks) + ' };')
o.append('constexpr Rc detCap = %s; constexpr const char* detCapText = %s;' % (rc(g[2]['capR']), q(g[2]['cap'])))
o.append('constexpr const char* hpTip = %s;' % q(g[2]['keys'][0]['tip']))
o.append('constexpr Rc dispCaps[3] = { ' + ', '.join(rc(c['r']) for c in d['dcaps']) + ' };')
o.append('constexpr const char* dispCapText[3] = { ' + ', '.join(q(c['t']) for c in d['dcaps']) + ' };')
o.append('constexpr Rc meterCaps[2] = { ' + ', '.join(rc(c['r']) for c in d['mcaps']) + ' };')
for k in ['brand', 'pPrev', 'pName', 'pNext', 'pSave', 'bBypass', 'bGuide', 'bSettings', 'bAbout', 'vu', 'cvCurve', 'cvHist', 'cvTime', 'cvIn', 'cvOut', 'pkIn', 'pkOut', 'cheek', 'mixKnob']:
    o.append('constexpr const char* tip_%s = %s;' % (k, q(d['tips'][k])))
o.append('} // namespace layout')
open('src/editor/Layout.h', 'w').write('\n'.join(o) + '\n')
print('ok H =', H)
